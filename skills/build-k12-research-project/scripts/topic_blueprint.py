def profile_for_subject(subject: str) -> SubjectProfile:
    normalized = subject.strip()
    exact = [profile for profile in PROFILES if normalized in profile.aliases]
    if exact:
        return exact[0]
    for profile in PROFILES:
        if any(alias in normalized or normalized in alias for alias in profile.aliases):
            return profile
    return GENERIC_PROFILE


def focus_for_problem(profile: SubjectProfile, problem: str) -> str:
    for term in profile.focus_terms:
        if term in problem:
            return FOCUS_LABELS.get(profile.key, {}).get(term, f"{term}能力")
    return profile.default_focus
